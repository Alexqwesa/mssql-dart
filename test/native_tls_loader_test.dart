import 'dart:io';
import 'dart:isolate';
import 'dart:typed_data';

import 'package:mssql_driver_with_native_tls/src/native_tls/native_tls_asset.dart';
import 'package:mssql_driver_with_native_tls/src/native_tls/native_tls_loader.dart';
import 'package:test/test.dart';

void main() {
  group('native TLS library lookup', () {
    test('uses a stable code-asset id', () {
      expect(
        nativeTlsAssetId,
        'package:mssql_driver_with_native_tls/src/native_tls/native_tls_loader.dart',
      );
    });

    test('uses the Android linker name without desktop fallback paths', () {
      expect(nativeTlsLibraryName('android'), 'libmssql_tls.so');
      expect(
        nativeTlsLibraryCandidates(
          operatingSystem: 'android',
          currentDirectory: '/unused',
          pathSeparator: '/',
        ),
        ['libmssql_tls.so'],
      );
    });

    test('uses dylibs and architecture-specific macOS fallbacks', () {
      expect(nativeTlsLibraryName('macos'), 'libmssql_tls.dylib');
      expect(nativeTlsLibraryName('ios'), 'libmssql_tls.dylib');
      expect(
        nativeTlsLibraryCandidates(
          operatingSystem: 'macos',
          currentDirectory: '/project',
          pathSeparator: '/',
          architecture: 'arm64',
        ),
        ['libmssql_tls.dylib', '/project/dist/macos/arm64/libmssql_tls.dylib'],
      );
      expect(
        nativeTlsLibraryCandidates(
          operatingSystem: 'ios',
          currentDirectory: '/unused',
          pathSeparator: '/',
          architecture: 'arm64',
        ),
        ['libmssql_tls.dylib'],
      );
    });

    test('puts an explicit override before the Android linker name', () {
      expect(
        nativeTlsLibraryCandidates(
          operatingSystem: 'android',
          currentDirectory: '/unused',
          pathSeparator: '/',
          override: '/data/local/tmp/libmssql_tls.so',
        ),
        ['/data/local/tmp/libmssql_tls.so', 'libmssql_tls.so'],
      );
    });

    test('keeps the checked-out helper fallback for desktop development', () {
      expect(
        nativeTlsLibraryCandidates(
          operatingSystem: 'linux',
          currentDirectory: '/project',
          pathSeparator: '/',
        ),
        ['libmssql_tls.so', '/project/native/bin/linux-x64/libmssql_tls.so'],
      );
    });
  });

  group('dart run / dart test runs on Windows', () {
    const id =
        'package:mssql_driver_with_native_tls/src/native_tls/native_tls_loader.dart';
    // What the Dart tool writes to .dart_tool/native_assets.yaml.
    const mapping =
        """
# Native assets mapping for host OS in JIT mode.
# Generated by dartdev and package:hooks_runner.

{
  "format-version": [1, 0, 0],
  "native-assets": {
    "windows_x64": {
      "$id": ["absolute", "C:\\\\app\\\\.dart_tool\\\\lib\\\\mssql_tls.dll"]
    }
  }
}""";

    test('find the bundled helper in the native-assets mapping', () {
      expect(
        nativeAssetPathFromMapping(mapping, target: 'windows_x64', assetId: id),
        r'C:\app\.dart_tool\lib\mssql_tls.dll',
      );
      expect(
        nativeAssetPathFromMapping(mapping, target: 'linux_x64', assetId: id),
        isNull,
      );
      expect(
        nativeAssetPathFromMapping(
          mapping,
          target: 'windows_x64',
          assetId: 'package:other/x.dart',
        ),
        isNull,
      );
      expect(
        nativeAssetPathFromMapping('{}', target: 'windows_x64', assetId: id),
        isNull,
      );
    });

    test(
      'concurrent isolates publish complete copies without collisions',
      () async {
        final temp = Directory.systemTemp.createTempSync('mssql_tls_isolates');
        addTearDown(() => temp.deleteSync(recursive: true));
        final bytes = Uint8List(4 * 1024 * 1024)
          ..fillRange(0, 4 * 1024 * 1024, 42);
        final bundled = File('${temp.path}/mssql_tls.dll')
          ..writeAsBytesSync(bytes);

        // Repeat cold-cache starts: the race disappears once the copy exists.
        for (var trial = 0; trial < 10; trial++) {
          final root = Directory('${temp.path}/copies$trial');
          final paths = await _concurrentCopies(bundled.path, root.path);
          expect(paths.toSet(), hasLength(1));
          expect(File(paths.first).readAsBytesSync(), bytes);
          expect(
            root.listSync(recursive: true).whereType<File>().map((f) => f.path),
            [paths.first],
            reason: 'temporary files must be cleaned up',
          );
          expect(
            root.listSync(recursive: true).whereType<Directory>(),
            hasLength(2),
            reason: 'only the package and content-hash directories remain',
          );
        }
      },
    );

    test('load a private copy named by content, never written again', () {
      final temp = Directory.systemTemp.createTempSync('mssql_tls_copy_test');
      addTearDown(() => temp.deleteSync(recursive: true));
      final bundled = File('${temp.path}${Platform.pathSeparator}mssql_tls.dll')
        ..writeAsBytesSync([1, 2, 3]);
      final root = Directory('${temp.path}${Platform.pathSeparator}copies');

      final first = privateNativeTlsCopy(bundled, root: root);
      expect(first, isNot(bundled.path));
      expect(File(first).readAsBytesSync(), [1, 2, 3]);
      expect(first, endsWith('${Platform.pathSeparator}mssql_tls.dll'));

      // A process has the copy open (loaded): the same helper reuses it, and the bundled file can be replaced.
      final inUse = File(first).openSync();
      addTearDown(inUse.closeSync);
      expect(privateNativeTlsCopy(bundled, root: root), first);
      bundled.writeAsBytesSync([4, 5, 6]);

      final changed = privateNativeTlsCopy(bundled, root: root);
      expect(
        changed,
        isNot(first),
        reason: 'a changed helper gets its own folder',
      );
      expect(File(changed).readAsBytesSync(), [4, 5, 6]);
      expect(File(first).readAsBytesSync(), [1, 2, 3]);
    });
  });
}

Future<List<String>> _concurrentCopies(String source, String root) async {
  const count = 16;
  final ready = ReceivePort();
  final sendPort = ready.sendPort;
  final starts = <SendPort>[];
  ready.listen((message) {
    starts.add(message as SendPort);
    if (starts.length == count) {
      for (final start in starts) {
        start.send(null);
      }
    }
  });
  try {
    return await Future.wait([
      for (var i = 0; i < count; i++)
        Isolate.run(() => _copyAfterSignal(source, root, sendPort)),
    ]);
  } finally {
    ready.close();
  }
}

Future<String> _copyAfterSignal(
  String source,
  String root,
  SendPort ready,
) async {
  final start = ReceivePort();
  ready.send(start.sendPort);
  await start.first;
  start.close();
  return privateNativeTlsCopy(File(source), root: Directory(root));
}
